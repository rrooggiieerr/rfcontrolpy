def test_decode_1() -> None:
    decoded = shutter1.decode(
        "32010110010101011001010101010101100110101001011010100101100101011001010110010101103201011001010101100101010101010110011010100101101010010110010101100101011001010114"
    )
    assert decoded == {"id": 276871624, "command": "up"}


